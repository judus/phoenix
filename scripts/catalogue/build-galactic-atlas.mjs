// Rebuild the small, offline atlas from pinned MIT-licensed region data.
// Usage: node scripts/catalogue/build-galactic-atlas.mjs
import { writeFile } from 'node:fs/promises'

const revision = '6c1191a58e1e593966f44f16235ab39d1ad24d84'
const base = `https://raw.githubusercontent.com/klightspeed/EliteDangerousRegionMap/${revision}/`
async function download(name) {
  const response = await fetch(base + name)
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`)
  return response.text()
}
const [svg, json] = await Promise.all([download('RegionMap.svg'), download('RegionMapData.json')])
const { regions: names, regionmap } = JSON.parse(json)
const labels = [...svg.matchAll(/<text class="regionText" style="transform: translate\((\d+)px, (\d+)px\)[^"]*">(.*?)<\/text>/gs)]
  .map(match => ({ x: +match[1], y: +match[2], name: match[3].replace(/<\/tspan>/g, ' ').replace(/<[^>]+>/g, '').trim().replace(/\s+/g, ' ') }))
const regions = [...svg.matchAll(/<path id="Region_(\d+)" class="region"\s+d="([^"]+)"/gs)].map(match => {
  const id = +match[1]
  const numbers = match[2].match(/\d+(?:\.\d+)?/g).map(Number)
  // Upstream contours contain degenerate cubics (start,start/end,end): retain their endpoints.
  const points = [[numbers[0], numbers[1]]]
  for (let i = 2; i < numbers.length; i += 6) points.push([numbers[i + 4], numbers[i + 5]])
  const outline = simplify(points, 0.7)
  const label = labels.find(label => label.name.replace(/- /g, '-') === names[id] || label.name === `The ${names[id]}`)
  if (!label || outline.some(point => point.some(value => !Number.isFinite(value)))) throw new Error(`Invalid region ${id}`)
  return { id, name: names[id], label: [label.x, label.y], path: `M${outline.map(point => point.join(',')).join('L')}Z` }
})
if (regions.length !== 42 || regionmap.length !== 2048) throw new Error('Unexpected region source format')
const boundaries = svg.match(/<path class="borderlines"\s+d="([^"]+)"/s)[1].replace(/\s+/g, ' ').trim()
const output = `// Generated by scripts/catalogue/build-galactic-atlas.mjs. Do not edit manually.
// Source: klightspeed/EliteDangerousRegionMap @ ${revision}
// MIT, Copyright (c) 2020 Ben Peddell. See licenses/EliteDangerousRegionMap.txt.
export const atlasRegions: { id: number, name: string, label: number[], path: string }[] = ${JSON.stringify(regions)}
export const atlasBoundaries = ${JSON.stringify(boundaries)}
export const atlasRegionRows: number[][][] = ${JSON.stringify(regionmap)}
`
await writeFile(new URL('../../apps/web/src/features/galaxy/atlas-region-data.ts', import.meta.url), output)
console.log(`Generated ${regions.length} regions (${output.length} bytes)`)

function simplify(points, tolerance) {
  if (points.length <= 2) return points
  const first = points[0], last = points.at(-1)
  const dx = last[0] - first[0], dy = last[1] - first[1], length = dx * dx + dy * dy
  let farthest = tolerance * tolerance, index = 0
  for (let i = 1; i < points.length - 1; i++) {
    const point = points[i]
    const t = length ? Math.max(0, Math.min(1, ((point[0] - first[0]) * dx + (point[1] - first[1]) * dy) / length)) : 0
    const distance = (point[0] - first[0] - t * dx) ** 2 + (point[1] - first[1] - t * dy) ** 2
    if (distance > farthest) { farthest = distance; index = i }
  }
  return index ? [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)] : [first, last]
}
